import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { blankEntry } from '../src/types.ts';
import { createEncryption, decryptWallet } from '../src/storage.ts';
const base = 'http://localhost:5173';
const credentials = JSON.parse(await readFile('.secrets/local-credentials.json', 'utf8'));
const call = async (path, method = 'GET', data, token = '', origin = base) => {
  const response = await fetch(base + '/api/' + path, { method, headers: { Origin: origin, ...(data === undefined ? {} : {'Content-Type':'application/json'}), ...(token ? {Cookie:token} : {}) }, body:data === undefined ? undefined : JSON.stringify(data) });
  return { status:response.status, data:await response.json(), cookie:response.headers.get('set-cookie'), headers:response.headers };
};
assert.equal((await call('wallet')).status,401);
assert.equal((await call('login','POST',credentials,'','https://other.example')).status,403);
assert.equal((await call('login','POST',{...credentials,password:'wrong'})).status,401);
let login=await call('login','POST',credentials); assert.equal(login.status,200);assert.match(login.cookie,/HttpOnly/);assert.match(login.cookie,/SameSite=Strict/);
const token=login.cookie.split(';')[0];
const second=(await call('login','POST',credentials)).cookie.split(';')[0];
assert.equal((await call('session','GET',undefined,token)).data.username,credentials.username);
let loaded=await call('wallet','GET',undefined,token);const initial=loaded.data;
assert.equal(loaded.headers.get('cache-control'),'no-store');
assert.equal((await call('wallet','PUT',{revision:initial.revision,payload:{broken:true}},token)).status,400);
const card={...blankEntry('bank'),name:'SQLite test',number:'4242',notes:'云端测试 🌏'};
const wallet={version:1,entries:[card],updatedAt:new Date().toISOString()};
const saved=await call('wallet','PUT',{revision:initial.revision,payload:wallet},token);assert.equal(saved.status,200);
assert.equal((await call('wallet','PUT',{revision:initial.revision,payload:{...wallet,entries:[]}},second)).status,409);
loaded=await call('wallet','GET',undefined,second);assert.deepEqual(loaded.data.payload,wallet);
const enc=await createEncryption(wallet,'local-test-vault-password');
assert.equal((await call('wallet','PUT',{revision:loaded.data.revision,payload:enc.envelope},token)).status,200);
loaded=await call('wallet','GET',undefined,token);assert.equal((await decryptWallet(loaded.data.payload,'local-test-vault-password')).wallet.entries[0].name,card.name);
// Exercise multiple D1 chunks and Unicode round-trips, then race two devices.
const large={...wallet,entries:Array.from({length:180},(_,i)=>({...card,id:'chunk-'+i,notes:'中🌏'.repeat(1400)}))};
assert.equal((await call('wallet','PUT',{revision:loaded.data.revision,payload:large},token)).status,200);
loaded=await call('wallet','GET',undefined,token);assert.deepEqual(loaded.data.payload,large);
const racing=await Promise.all([token,second].map(t=>call('wallet','PUT',{revision:loaded.data.revision,payload:wallet},t)));
assert.deepEqual(racing.map(r=>r.status).sort(),[200,409]);
loaded=await call('wallet','GET',undefined,token);
assert.equal((await call('wallet','PUT',{revision:loaded.data.revision,payload:initial.payload},token)).status,200);
assert.equal((await call('password','POST',{currentPassword:'wrong',newPassword:'local-changed-passphrase'},token)).status,400);
assert.equal((await call('password','POST',{currentPassword:credentials.password,newPassword:'local-changed-passphrase'},token)).status,200);
assert.equal((await call('session','GET',undefined,second)).status,401);
assert.equal((await call('login','POST',credentials)).status,401);
login=await call('login','POST',{...credentials,password:'local-changed-passphrase'});assert.equal(login.status,200);
assert.equal((await call('password','POST',{currentPassword:'local-changed-passphrase',newPassword:credentials.password},login.cookie.split(';')[0])).status,200);
login=await call('login','POST',credentials);
assert.equal((await call('logout','POST',undefined,login.cookie.split(';')[0])).status,200);
assert.equal((await call('session','GET',undefined,login.cookie.split(';')[0])).status,401);
for(let i=0;i<10;i++) assert.equal((await call('login','POST',{...credentials,password:'wrong'})).status,401);
assert.equal((await call('login','POST',credentials)).status,429);
console.log('PASS: auth, CSRF, cookies, SQLite CRUD, conflict/race protection, encryption, multi-chunk Unicode, password rotation, logout and rate limits.');
