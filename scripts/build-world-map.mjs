import { writeFile } from 'node:fs/promises';

// Public-domain coastlines and Google's canonical country coordinates; see docs/MAP_DATA.md.
const landUrl = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson';
const coordinatesUrl = 'https://raw.githubusercontent.com/google/dspl/master/samples/google/canonical/countries.csv';
const download = async url => {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  return response.text();
};
const [landText, coordinateText] = await Promise.all([download(landUrl), download(coordinatesUrl)]);
const point = ([lng, lat]) => `${((lng + 180) / 360 * 1000).toFixed(1)},${((90 - lat) / 360 * 1000).toFixed(1)}`;
const paths = JSON.parse(landText).features.flatMap(({ geometry }) => {
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  return polygons.filter(polygon => polygon[0].some(([, lat]) => lat > -60)).map(polygon =>
    polygon.map(ring => `M${ring.map(point).join('L')}Z`).join(''));
});
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 450" fill="none"><defs><pattern id="land-dots" width="5" height="5" patternUnits="userSpaceOnUse"><circle cx="2" cy="2" r=".8" fill="#b7b7bf"/></pattern></defs><g fill="#f5f5f6" stroke="#e8e8eb" stroke-width=".6">${paths.map(d=>`<path d="${d}"/>`).join('')}</g><g fill="url(#land-dots)">${paths.map(d=>`<path d="${d}"/>`).join('')}</g></svg>`;
const coordinates = {};
for (const line of coordinateText.trim().split(/\r?\n/).slice(1)) {
  const [code, latitude, longitude] = line.split(',');
  if (/^[A-Z]{2}$/.test(code) && latitude && longitude && Number.isFinite(Number(latitude)) && Number.isFinite(Number(longitude))) {
    coordinates[code] = [Number(longitude), Number(latitude)];
  }
}
await writeFile(new URL('../public/world-map.svg', import.meta.url), svg);
await writeFile(new URL('../src/region-coordinates.ts', import.meta.url), `// Generated by scripts/build-world-map.mjs. Coordinates are [longitude, latitude].\n// See docs/MAP_DATA.md for sources; this is a region overview, not address geocoding.\nexport const regionCoordinates: Readonly<Record<string, readonly [number, number]>> = ${JSON.stringify(coordinates, null, 2)};\n`);
console.log(`World map: ${paths.length} coastline paths, ${Object.keys(coordinates).length} region positions, ${Buffer.byteLength(svg)} SVG bytes.`);
